import {test} from 'node:test';
import assert from 'node:assert/strict';
import {createModeration} from './moderation.mjs';
import {mkdtempSync,rmSync} from 'node:fs';
import {tmpdir} from 'node:os';
import path from 'node:path';
const owner={id:'owner',email:'bgm38388@gmail.com',emailVerified:true};
const member={id:'member',email:'helper@example.com',emailVerified:true};
test('only configured owner grants/revokes admins; revocation takes effect on existing sessions',async t=>{
 const m=(await createModeration({database:':memory:',adminEmails:[owner.email]}));t.after(async ()=>(await m.close()));
 assert.equal((await m.isAdmin(member)),false);
 (await m.addAdmin(owner,'  HELPER@EXAMPLE.COM  '));
 assert.equal((await m.isAdmin(member)),true);assert.equal((await m.isOwner(member)),false);
 assert.equal((await m.list(member)).length,0);
 (await assert.rejects(async ()=>(await m.addAdmin(member,'next@example.com')),/chủ sở hữu/i));
 (await assert.rejects(async ()=>(await m.removeAdmin(member,owner.email)),/chủ sở hữu/i));
 (await assert.rejects(async ()=>(await m.adminMembers(member)),/chủ sở hữu/i));
 (await assert.rejects(async ()=>(await m.addAdmin({...owner,emailVerified:false},member.email)),/chủ sở hữu/i));
 (await assert.rejects(async ()=>(await m.addAdmin(null,member.email)),/đăng nhập/i));
 (await assert.rejects(async ()=>(await m.removeAdmin(owner,owner.email)),/chủ sở hữu/i));
 (await assert.rejects(async ()=>(await m.addAdmin(owner,'bad-address')),/email/i));
 (await assert.rejects(async ()=>(await m.addAdmin(owner,member.email)),/đã có/i));
 assert.equal((await m.isAdmin({...member,emailVerified:false})),false);
 (await m.removeAdmin(owner,member.email));
 assert.equal((await m.isAdmin(member)),false);(await assert.rejects(async ()=>(await m.list(member)),/admin/i));
 assert.equal((await m.isAdmin(owner)),true);
});
test('admin grants persist across restart and owner membership is protected',async t=>{
 const dir=mkdtempSync(path.join(tmpdir(),'dfl-admin-')),database=path.join(dir,'cards.sqlite');let m=(await createModeration({database,adminEmails:[owner.email]}));
 t.after(async ()=>{(await m.close());rmSync(dir,{recursive:true,force:true});});
 (await m.addAdmin(owner,member.email));(await m.close());m=(await createModeration({database,adminEmails:[owner.email]}));
 assert.equal((await m.isAdmin(member)),true);assert.equal((await m.adminMembers(owner)).length,2);
 assert.equal((await m.adminMembers(owner)).find(x=>x.email===owner.email).role,'owner');
 (await m.removeAdmin(owner,member.email));assert.equal((await m.adminMembers(owner)).length,1);
});
